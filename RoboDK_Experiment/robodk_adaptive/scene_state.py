from __future__ import annotations
from .models import *
from typing import Protocol
class Adapter(Protocol):
    def observe(self)->SceneSnapshot: ...
    def doctor(self)->dict: ...
    def reset(self)->None: ...
    def move_to(self,target_id:str)->None: ...
    def pick(self,object_id:str)->None: ...
    def place(self,object_id:str,slot_id:str)->None: ...
    def is_simulation(self)->bool: ...
class SceneObserver:
    def __init__(self,adapter:Adapter,pos_tol=2.0,rot_tol=2.0): self.adapter=adapter; self.pos_tol=pos_tol; self.rot_tol=rot_tol; self.last=None
    def read(self):
        current=self.adapter.observe(); changed=self.last is not None and self.changed(self.last,current); self.last=current; return current,changed
    def changed(self,old,new):
        for key,part in old.parts.items():
            other=new.parts.get(key)
            if other is None or part.available!=other.available or part.parent!=other.parent or part.pose.changed(other.pose,self.pos_tol,self.rot_tol): return True
        return old.robot.held_object!=new.robot.held_object
